"""Optional real CLI smoke test against a loopback fixture, with no model/API key.

Runs an isolated, non-interactive Codex process. Trust bypass applies only to
the temporary hooks generated by this test, never to the user's configuration.
"""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile
import threading

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from mxbridge.install import definition
from mxbridge.state import EVENTS, Store


class Fixture(BaseHTTPRequestHandler):
    def log_message(self, *_args):
        pass

    def do_POST(self):
        self.rfile.read(int(self.headers.get("Content-Length", 0)))
        item = dict(id="msg_fixture", type="message", role="assistant", status="completed",
                    content=[dict(type="output_text", text="Fixture complete.", annotations=[])])
        response = dict(id="resp_fixture", object="response", status="completed", output=[item],
                        usage=dict(input_tokens=1, output_tokens=1, total_tokens=2))
        events = [dict(type="response.created", response=dict(response, status="in_progress", output=[])),
                  dict(type="response.output_item.done", output_index=0, item=item),
                  dict(type="response.completed", response=response)]
        data = "".join("event: " + e["type"] + "\ndata: " + json.dumps(e) + "\n\n" for e in events).encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


def main():
    binary = shutil.which(os.environ.get("CODEX_TEST_BIN", "codex"))
    if not binary:
        print("SKIP: Codex CLI not installed")
        return 0
    server = ThreadingHTTPServer(("127.0.0.1", 0), Fixture)
    worker = threading.Thread(target=server.serve_forever, daemon=True)
    worker.start()
    try:
        with tempfile.TemporaryDirectory(prefix="mx-cli-smoke-") as folder:
            root = Path(folder)
            home, state, cwd = root/"codex", root/"state", root/"cwd"
            home.mkdir(); cwd.mkdir()
            events = root/"events.txt"
            observer = root/"observer.py"
            observer.write_text(
                "import json,subprocess,sys\n"
                "from pathlib import Path\n"
                "raw=sys.stdin.buffer.read()\n"
                "p=json.loads(raw)\n"
                f"with open({str(events)!r},'a') as f: f.write(p.get('hook_event_name','?')+'\\n')\n"
                f"subprocess.run([{sys.executable!r},{str(ROOT/'bridge.py')!r},'hook'],input=raw,check=True)\n",
                encoding="utf-8")
            config = definition(ROOT/"bridge.py")
            for event in EVENTS:
                handler = config["hooks"][event][0]["hooks"][0]
                handler["command"] = shlex.join([sys.executable, str(observer)])
                if os.name == "nt":
                    handler["commandWindows"] = subprocess.list2cmdline([sys.executable, str(observer)])
            (home/"hooks.json").write_text(json.dumps(config), encoding="utf-8")
            # Never load user credentials, skills, plugins, MCP servers, or settings.
            (home/"config.toml").write_text(
                'model="fixture"\nmodel_provider="fixture"\nweb_search="disabled"\n'
                '[features]\nhooks=true\n'
                '[model_providers.fixture]\nname="Loopback test"\n'
                f'base_url="http://127.0.0.1:{server.server_port}/v1"\n'
                'wire_api="responses"\nrequires_openai_auth=false\n'
                'request_max_retries=0\nstream_max_retries=0\n', encoding="utf-8")
            env = dict(os.environ, CODEX_HOME=str(home), MX_CODEX_STATE_DIR=str(state))
            for name in ("OPENAI_API_KEY", "CODEX_API_KEY", "OPENAI_BASE_URL", "OPENAI_ORG_ID"):
                env.pop(name, None)
            argv = [binary, "exec", "--skip-git-repo-check", "--dangerously-bypass-hook-trust",
                    "--ephemeral", "-s", "read-only", "-C", str(cwd), "Return the fixture message."]
            result = subprocess.run(argv, env=env, stdin=subprocess.DEVNULL, capture_output=True, timeout=45)
            observed = events.read_text().splitlines() if events.exists() else []
            required = {"SessionStart", "UserPromptSubmit", "Stop"}
            if result.returncode or not required.issubset(observed):
                print(result.stderr.decode(errors="replace")[-6000:])
                raise RuntimeError(f"CLI exit={result.returncode}; observed={observed}")
            rows = Store(state).read()["rows"]
            assert len(rows) == 1, rows
            assert rows[0]["last_event"] in {"Stop", "SessionEnd"}, rows
            print("PASS: real Codex CLI emitted " + ", ".join(observed))
            print("PASS: fixture events reached the bridge state file")
            print("Not tested here: interactive permissions, subagent/compaction/interrupt hooks, macOS TUI.")
    finally:
        server.shutdown()
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
